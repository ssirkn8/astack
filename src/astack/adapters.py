"""Generate thin native discovery wrappers, never copies of skill semantics."""

from __future__ import annotations

import argparse
import hashlib
import subprocess
from pathlib import Path

import yaml

from .components import NATIVE_DISCOVERY_ROOTS, Component, component_source, load_components

HARNESSES = ("opencode", "pi", "codex", "claude-code")
DISCOVERY_ROOTS = NATIVE_DISCOVERY_ROOTS


def skill_wrapper(source: bytes, canonical_path: str) -> bytes:
    """Keep discovery metadata while loading the authoritative skill on demand."""
    text = source.decode("utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"Missing skill metadata: {canonical_path}")
    metadata = yaml.safe_load(text.split("---", 2)[1])
    if not isinstance(metadata, dict) or not all(
        isinstance(metadata.get(key), str) for key in ("name", "description")
    ):
        raise ValueError(f"Invalid skill metadata: {canonical_path}")
    header = yaml.safe_dump(
        {key: metadata[key] for key in ("name", "description")}, sort_keys=False
    )
    return (
        f"---\n{header}---\n\n"
        "<!-- Generated by astack.adapters. Do not edit. -->\n\n"
        f"Read `{canonical_path}` from the repository root before acting. "
        "That file is the complete authoritative capability, including its supporting references. "
        "Resolve referenced repository paths from the root, not this wrapper directory.\n\n"
        "A command spelling is not authority. If native discovery, context, tools, or human "
        "interaction cannot satisfy the canonical skill, stop with a specific blocker. "
        "Never substitute tool permission for human approval.\n"
    ).encode()


def component_bytes(root: Path, component: Component) -> bytes:
    path = component_source(root, component)
    source = path.read_bytes()
    if component.kind == "upstream":
        if (
            path.is_symlink()
            or hashlib.sha256(source).hexdigest() != component.sha256
            or bool(path.stat().st_mode & 0o111) != component.executable
        ):
            raise ValueError(f"Upstream integrity mismatch: {component.source}")
        return source
    if component.kind == "generated-adapter":
        return skill_wrapper(source, f".opencode/{component.source}")
    return source


def native_adapters(root: Path, *, maintainer: bool) -> dict[str, bytes]:
    """Generate from canonical authored skills, including shared helper capabilities."""
    skills = root / ".opencode/skills"
    if not skills.exists():
        skills = root / "opencode/skills"
    result = {}
    project_sources = {
        component.source
        for component in load_components(root)
        if component.kind == "opencode" and component.source.startswith("skills/")
    }
    for source in sorted(skills.glob("*/SKILL.md")):
        name = source.parent.name
        if not maintainer and f"skills/{name}/SKILL.md" not in project_sources:
            continue
        for discovery in DISCOVERY_ROOTS.values():
            result[f"{discovery}/{name}/SKILL.md"] = skill_wrapper(
                source.read_bytes(), f".opencode/skills/{name}/SKILL.md"
            )
    return result


def maintainer_upstream_copies(root: Path) -> dict[str, tuple[bytes, bool]]:
    """Byte-identical copies of the pinned skills for Claude Code, which reads only .claude/skills.

    Codex, OpenCode and Pi already read the canonical locked copies under `.agents/skills`.
    """
    from .upstream_skills import LOCK, payload

    if not (root / LOCK).is_file():
        return {}
    return {
        f"{NATIVE_DISCOVERY_ROOTS['claude-code']}/{relative}": (data, executable)
        for relative, (data, executable) in payload(root).items()
        if not relative.startswith(".astack-notices/")
    }


def orphaned_wrappers(root: Path, expected: set[str]) -> list[str]:
    """Generated wrappers whose authored skill was removed. Delete them by hand."""
    orphans = []
    for discovery in sorted(set(DISCOVERY_ROOTS.values())):
        for path in sorted((root / discovery).glob("*/SKILL.md")):
            relative = path.relative_to(root).as_posix()
            if relative not in expected and b"Generated by astack.adapters" in path.read_bytes():
                orphans.append(f"{relative} (orphaned: its authored skill is gone)")
    return orphans


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    drift = []
    writes: list[tuple[Path, bytes, bool | None]] = []
    targets: dict[str, tuple[bytes, bool | None]] = {
        relative: (data, None) for relative, data in native_adapters(root, maintainer=True).items()
    }
    targets.update(maintainer_upstream_copies(root))
    for relative, (data, executable) in targets.items():
        path = root / relative
        if args.check:
            if (
                not path.is_file()
                or path.read_bytes() != data
                or executable is not None
                and bool(path.stat().st_mode & 0o111) != executable
            ):
                drift.append(relative)
        else:
            # Never replace a customized file or follow a user-owned symlink.
            if path.is_symlink() or any(p.is_symlink() for p in path.parents if p != root):
                raise ValueError(f"Unsafe adapter target: {relative}")
            if path.exists():
                current = path.read_bytes()
                if current == data:
                    if executable is not None:
                        writes.append((path, data, executable))
                    continue
                # A marker alone is not ownership evidence. Preserve modified or unknown
                # files, including customized generated wrappers, before writing anything.
                baseline = subprocess.run(
                    ["git", "show", f"HEAD:{relative}"],
                    cwd=root,
                    capture_output=True,
                    check=False,
                )
                generated = executable is not None or b"Generated by astack.adapters" in (
                    baseline.stdout
                )
                if baseline.returncode != 0 or current != baseline.stdout or not generated:
                    raise ValueError(f"Preserve customized or unknown adapter: {relative}")
            writes.append((path, data, executable))
    drift.extend(orphaned_wrappers(root, set(targets)))
    if drift:
        raise SystemExit("Adapter drift: " + ", ".join(drift))
    for path, data, executable in writes:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        if executable is not None:
            path.chmod(0o755 if executable else 0o644)


if __name__ == "__main__":
    main()
