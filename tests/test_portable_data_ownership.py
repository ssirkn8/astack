"""Project-owned durable inputs permit native worktree retirement without a lifecycle engine."""

import hashlib
import importlib.util
import json
from pathlib import Path
from typing import Any

import pytest
from git_test_support import _project, _run, create_linked_worktree, remove_linked_worktree

spec = importlib.util.spec_from_file_location(
    "project_pipeline", "tests/fixtures/portable-data/project_pipeline.py"
)
assert spec and spec.loader
pipeline = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pipeline)
pytestmark = pytest.mark.integration


def prepared(tmp_path):
    project = _project(tmp_path)
    raw = tmp_path / "external-drive"
    products = tmp_path / "frozen-products"
    raw.mkdir()
    products.mkdir()
    (raw / "measurements.csv").write_bytes(b"value\n2\n4\n")
    sources: dict[str, dict[str, Any]] = {
        "raw": {
            "path": "external://raw/measurements.csv",
            "raw_checksum": hashlib.sha256((raw / "measurements.csv").read_bytes()).hexdigest(),
        }
    }
    producer = project / "scripts/project_pipeline.py"
    producer.write_bytes(Path("tests/fixtures/portable-data/project_pipeline.py").read_bytes())
    _run(["git", "add", "scripts/project_pipeline.py"], project)
    _run(["git", "commit", "-m", "Install the project-owned fixture producer"], project)
    stage = create_linked_worktree(project, "render-stage", tmp_path / "stages")
    old = Path(stage["worktree"])
    stage_spec = importlib.util.spec_from_file_location(
        "actual_stage_producer", old / "scripts/project_pipeline.py"
    )
    assert stage_spec and stage_spec.loader
    actual_producer = importlib.util.module_from_spec(stage_spec)
    stage_spec.loader.exec_module(actual_producer)
    local_product = old / "data/processed/analysis/summary.json"
    local_product.parent.mkdir(parents=True, exist_ok=True)
    product = actual_producer.from_raw(raw, sources)
    local_product.write_bytes(product)
    assert product == pipeline.from_raw(raw, sources)  # Independent canonical recomputation.
    expected_product = hashlib.sha256(product).hexdigest()
    with (products / "summary.json").open("xb") as destination:
        destination.write(local_product.read_bytes())
    assert hashlib.sha256((products / "summary.json").read_bytes()).hexdigest() == expected_product
    sources["retained"] = {
        "path": "external://frozen-products/summary.json",
        "raw_checksum": expected_product,
        "reproduction_level": "render-retained-product",
        "historical_stage": stage["worktree"],
        "derivation": json.loads(product)["derivation"],
    }
    sources["baseline"] = {
        "path": "data/raw/source.bin",
        "raw_checksum": hashlib.sha256((project / "data/raw/source.bin").read_bytes()).hexdigest(),
    }
    for source_id, source in sources.items():
        source.update(
            {
                "title": f"Synthetic {source_id} fixture",
                "origin": "Generated by this test",
                "provider": "Test fixture",
                "access_date": "2026-11-03",
                "version": "fixture-1",
                "license": "Synthetic test fixture",
                "sensitivity": "public synthetic values",
                "allowed_outputs": ["test-render"],
                "redistribution": "test fixture only",
                "citation": "Portable data regression fixture",
                "acquisition": "Generate and freeze the synthetic fixture before rendering.",
            }
        )
    source_path = project / "data/sources.yml"
    source_path.write_text(json.dumps({"sources": sources}, indent=2))
    _run(["git", "add", "data/sources.yml"], project)
    _run(["git", "commit", "-m", "Freeze actual producer and input identities"], project)
    assert pipeline.render_retained(products, sources) == b"mean\n3\n"
    # Explicit fixture preservation, after verification. No product runtime grants this action.
    local_product.unlink()
    return project, raw, products, sources, stage


def deny_old_reads(monkeypatch, old):
    original = Path.open

    def guarded(path, *args, **kwargs):
        if path == old or old in path.parents:
            raise AssertionError("Retired-stage read attempted")
        return original(path, *args, **kwargs)

    monkeypatch.setattr(Path, "open", guarded)


def test_retired_worktree_absent_and_reads_denied_preserves_render_bytes(tmp_path, monkeypatch):
    project, raw, products, sources, stage = prepared(tmp_path)
    old = Path(stage["worktree"])
    before_provenance = (project / "data/sources.yml").read_bytes()
    expected = pipeline.render_retained(products, sources)
    assert expected == b"mean\n3\n"
    assert json.loads(pipeline.from_raw(raw, sources))["mean"] == "3"
    remove_linked_worktree(project, old)
    assert not old.exists()
    deny_old_reads(monkeypatch, old)
    with pytest.raises(AssertionError, match="Retired-stage"):
        (old / "data/processed/summary.json").read_bytes()
    assert pipeline.render_retained(products, sources) == expected
    assert (project / "data/sources.yml").read_bytes() == before_provenance


def test_missing_raw_drive_can_render_verified_product_not_rebuild_raw(tmp_path, monkeypatch):
    project, raw, products, sources, stage = prepared(tmp_path)
    old = Path(stage["worktree"])
    expected = pipeline.render_retained(products, sources)
    (raw / "measurements.csv").unlink()  # Only a disposable fixture drive is removed.
    raw.rmdir()
    with pytest.raises(ValueError, match="unavailable"):
        pipeline.from_raw(raw, sources)
    remove_linked_worktree(project, old)
    assert not old.exists()
    deny_old_reads(monkeypatch, old)
    assert pipeline.render_retained(products, sources) == expected
    assert sources["retained"]["reproduction_level"] == "render-retained-product"


@pytest.mark.parametrize("failure", ["missing", "mismatch", "symlink"])
def test_unverified_product_keeps_worktree_and_frozen_identity(tmp_path, failure):
    project, _, products, sources, stage = prepared(tmp_path)
    old = Path(stage["worktree"])
    product = products / "summary.json"
    frozen = (project / "data/sources.yml").read_bytes()
    if failure == "missing":
        product.unlink()
    elif failure == "mismatch":
        product.write_bytes(b"changed")
    else:
        elsewhere = products / "other.json"
        elsewhere.write_bytes(product.read_bytes())
        product.unlink()
        product.symlink_to(elsewhere)
    with pytest.raises(ValueError):
        pipeline.render_retained(products, sources)
    assert old.exists()  # No cleanup is attempted after failed project-owned verification.
    assert (project / "data/sources.yml").read_bytes() == frozen


def test_changed_raw_is_not_blessed_by_refreshing_its_checksum(tmp_path):
    project, raw, products, sources, stage = prepared(tmp_path)
    frozen = (project / "data/sources.yml").read_bytes()
    retained = (products / "summary.json").read_bytes()
    (raw / "measurements.csv").write_bytes(b"value\n20\n40\n")
    with pytest.raises(ValueError, match="identity mismatch"):
        pipeline.from_raw(raw, sources)
    assert Path(stage["worktree"]).exists()
    assert (project / "data/sources.yml").read_bytes() == frozen
    assert (products / "summary.json").read_bytes() == retained


def test_retained_byte_identity_does_not_substitute_for_derivation(tmp_path):
    import copy

    _, _, products, sources, _ = prepared(tmp_path)
    unbound = copy.deepcopy(sources)
    unbound["retained"]["derivation"]["input_sha256"] = "0" * 64
    with pytest.raises(ValueError, match="derivation"):
        pipeline.render_retained(products, unbound)
