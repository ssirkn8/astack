"""Build the self-contained runtime files vendored into generated projects."""

from __future__ import annotations

import argparse
import ast
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNTIME_MODULES = {
    "workflow/project_tool_bundle.py": (
        "workflow/project_runtime",
        (
            "project_state.py",
            "sources.py",
            "validation.py",
            "pipeline.py",
            "dependency_check.py",
            "reproduction.py",
            "staleness.py",
            "output_contract.py",
            "publication.py",
            "reports.py",
            "review.py",
            "review_outputs.py",
            "cli.py",
        ),
    ),
}


def _definitions(path: Path) -> str:
    """Return source definitions while excluding package-only import scaffolding."""
    source = path.read_text(encoding="utf-8")
    lines = source.splitlines(keepends=True)
    tree = ast.parse(source)
    chunks: list[str] = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            first = min([node.lineno, *(decorator.lineno for decorator in node.decorator_list)])
            chunks.append("".join(lines[first - 1 : node.end_lineno]).rstrip())
    return "\n\n".join(chunks)


def _bundle_core(path: Path) -> str:
    """Return the foundation source without split-module scaffolding or early exports."""
    source = path.read_text(encoding="utf-8")
    lines = source.splitlines(keepends=True)
    tree = ast.parse(source)
    removed: list[tuple[int, int]] = []
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and any(
                isinstance(target, ast.Name) and target.id == "__all__" for target in node.targets
            )
            and node.end_lineno is not None
        ):
            removed.append((node.lineno - 1, node.end_lineno))
        if isinstance(node, ast.If) and isinstance(node.test, ast.Name):
            if node.test.id == "TYPE_CHECKING" and node.end_lineno is not None:
                removed.append((node.lineno - 1, node.end_lineno))
    for start, end in reversed(removed):
        del lines[start:end]
    return "".join(lines).rstrip()


def _bundle(source_dir: Path, module_names: tuple[str, ...], *, executable: bool) -> str:
    core = _bundle_core(source_dir / "common.py")
    pieces = [
        "# Generated by scripts/build_runtime_bundles.py. Do not edit this bundle directly.",
        core.rstrip(),
    ]
    for module_name in module_names:
        path = source_dir / module_name
        body = _definitions(path)
        if body:
            pieces.extend([f"# --- {path.stem} responsibility ---", body])
    if executable:
        pieces.extend(['if __name__ == "__main__":', "    main()"])
    return "\n\n\n".join(pieces).rstrip() + "\n"


def build(*, check: bool) -> int:
    stale: list[str] = []
    for target_name, (source_dir_name, module_names) in RUNTIME_MODULES.items():
        target = ROOT / target_name
        source_dir = ROOT / source_dir_name
        expected = _bundle(
            source_dir,
            module_names,
            executable=target_name.endswith("project_tool_bundle.py"),
        )
        expected = subprocess.run(
            [sys.executable, "-m", "ruff", "format", "--stdin-filename", target_name, "-"],
            cwd=ROOT,
            input=expected,
            text=True,
            capture_output=True,
            check=True,
        ).stdout
        if check:
            if not target.is_file() or target.read_text(encoding="utf-8") != expected:
                stale.append(target_name)
        else:
            target.write_text(expected, encoding="utf-8")
    if stale:
        print("Runtime bundles are stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    if not check:
        print("Generated self-contained runtime bundles.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a runtime bundle is stale")
    args = parser.parse_args()
    return build(check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
